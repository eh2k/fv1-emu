// Assembles the .spn corpus into ROM images and a fixed input signal, emitted as
// a C header so the bare metal benchmark needs no filesystem and no libm.
#include <cstdio>
#include <cstring>
#include <cmath>
#include <string>
#include <vector>
#include "FV1emu.hpp"

int main(int argc, char **argv)
{
    if (argc < 3) { fprintf(stderr, "usage: spn2rom <out.h> <prog.spn>...\n"); return 2; }
    FILE *o = fopen(argv[1], "w");
    if (!o) { perror(argv[1]); return 1; }

    fprintf(o, "// generated by test/host/spn2rom.cpp - do not edit\n#pragma once\n#include <stdint.h>\n\n");

    std::vector<std::string> names;
    for (int a = 2; a < argc; ++a)
    {
        std::vector<uint32_t> rom(128);
        std::string display;
        std::stringstream buf;
        std::ifstream t(argv[a], std::ios::binary);
        buf << t.rdbuf();
        if (!SpnParser::asmSPN(buf.str(), rom, display)) { fprintf(stderr, "parse failed: %s\n", argv[a]); return 1; }

        const char *b = strrchr(argv[a], '/'); b = b ? b + 1 : argv[a];
        std::string id(b);
        id = id.substr(0, id.find('.'));
        for (auto &c : id) if (!isalnum((unsigned char)c)) c = '_';
        names.push_back(id);

        const uint8_t *p = (const uint8_t *)&rom[0];
        fprintf(o, "static const uint8_t rom_%s[512] = {", id.c_str());
        for (int i = 0; i < 512; ++i) fprintf(o, "%s%u,", i % 16 ? "" : "\n    ", p[i]);
        fprintf(o, "\n};\n\n");
    }

    fprintf(o, "typedef struct { const char *name; const uint8_t *rom; } FxProgram;\n");
    fprintf(o, "static const FxProgram PROGRAMS[] = {\n");
    for (auto &n : names) fprintf(o, "    {\"%s\", rom_%s},\n", n.c_str(), n.c_str());
    fprintf(o, "};\nstatic const int PROGRAM_COUNT = %d;\n\n", (int)names.size());

    // deterministic input signal, so the target needs no sinf()
    const int N = 1024;
    fprintf(o, "#define SIGNAL_LEN %d\nstatic const float SIGNAL_L[%d] = {", N, N);
    for (int i = 0; i < N; ++i)
        fprintf(o, "%s%.9ef,", i % 6 ? " " : "\n    ",
                0.6f * sinf(i * 0.031415926f) + 0.25f * sinf(i * 0.2293363f));
    fprintf(o, "\n};\nstatic const float SIGNAL_R[%d] = {", N);
    for (int i = 0; i < N; ++i)
        fprintf(o, "%s%.9ef,", i % 6 ? " " : "\n    ",
                0.5f * sinf(i * 0.0534070742f) - 0.3f * sinf(i * 0.00408407f));
    fprintf(o, "\n};\n");
    fclose(o);
    fprintf(stderr, "%s: %d programs\n", argv[1], (int)names.size());
    return 0;
}
